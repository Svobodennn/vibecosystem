function timestamp() {
  const now = new Date();
  const pad = (value) => String(value).padStart(2, '0');
  return `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}-${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
}

function assertRegularTarget(path) {
  if (!existsSync(path)) return;
  const stat = lstatSync(path);
  if (stat.isSymbolicLink()) throw new Error(`refusing to overwrite symlink: ${path}`);
  if (!stat.isFile()) throw new Error(`write target is not a regular file: ${path}`);
}

function isWithin(base, path) {
  const rel = relative(resolve(base), resolve(path));
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
}

function backupLabel(path) {
  if (isWithin(CODEX_HOME, path)) return join('codex', relative(resolve(CODEX_HOME), resolve(path)));
  if (isWithin(SKILLS_HOME, path)) return join('skills', relative(resolve(SKILLS_HOME), resolve(path)));
  throw new Error(`refusing to back up path outside managed roots: ${path}`);
}

function ensureBackupDirectory() {
  if (DRY || BACKUP_DIR) return;
  if (existsSync(BACKUP_ROOT)) {
    const stat = lstatSync(BACKUP_ROOT);
    if (stat.isSymbolicLink()) throw new Error(`refusing to use symlink backup root: ${BACKUP_ROOT}`);
    if (!stat.isDirectory()) throw new Error(`backup root is not a directory: ${BACKUP_ROOT}`);
  }
  mkdirSync(BACKUP_ROOT, { recursive: true });
  const stem = `${timestamp()}-${process.pid}`;
  let candidate = join(BACKUP_ROOT, stem);
  let suffix = 0;
  while (existsSync(candidate)) {
    suffix += 1;
    candidate = join(BACKUP_ROOT, `${stem}-${suffix}`);
  }
  mkdirSync(candidate);
  BACKUP_DIR = candidate;
}

function backupExistingPath(path) {
  if (!existsSync(path)) return;
  const absolute = resolve(path);
  if (BACKED_UP_PATHS.has(absolute)) return;
  const stat = lstatSync(path);
  if (stat.isSymbolicLink()) throw new Error(`refusing to back up symlink: ${path}`);
  const label = backupLabel(path);
  BACKUP_PLANNED = true;
  BACKED_UP_PATHS.add(absolute);
  if (DRY) return;
  ensureBackupDirectory();
  let candidate = join(BACKUP_DIR, label);
  let suffix = 0;
  mkdirSync(dirname(candidate), { recursive: true });
  while (existsSync(candidate)) {
    suffix += 1;
    candidate = `${join(BACKUP_DIR, label)}.${suffix}`;
  }
  cpSync(path, candidate, { recursive: true, preserveTimestamps: true });
}

function hasOwnershipMarker(body, marker, mode) {
  if (!marker) return true;
  return mode === 'includes' ? body.includes(marker) : body.startsWith(marker);
}

function assertWritable(path, { marker = '', markerMode = 'startsWith' } = {}) {
  if (!existsSync(path)) return;
  assertRegularTarget(path);
  if (marker && !hasOwnershipMarker(readFileSync(path, 'utf8'), marker, markerMode) && !FORCE) {
    throw new Error(`refusing to overwrite unmanaged file without --force: ${path}`);
  }
}

function write(path, body, options = {}) {
  assertWritable(path, options);
  backupExistingPath(path);
  if (DRY) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body);
}

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

function readJson(path, label) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    throw new Error(`${label} is not valid JSON: ${path}: ${error.message}`);
  }
}

function flatMarkdownFiles(dir, label, { ignoreDotfiles = false } = {}) {
  if (!existsSync(dir)) throw new Error(`${label} directory is missing: ${dir}`);
  const entries = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => !(ignoreDotfiles && entry.name.startsWith('.')));
  const invalid = entries.filter((entry) => !entry.isFile() || !entry.name.endsWith('.md'));
  if (invalid.length) {
    throw new Error(`${label} must be flat and contain only .md files: ${invalid.map((entry) => entry.name).join(', ')}`);
  }
  return entries.map((entry) => entry.name).sort();
}

function assertSameSet(actual, expected, label) {
  const missing = [...expected].filter((item) => !actual.has(item));
  const extra = [...actual].filter((item) => !expected.has(item));
  if (missing.length || extra.length) {
    throw new Error(`${label} mismatch; missing=[${missing.join(', ')}] extra=[${extra.join(', ')}]`);
  }
}

function readValidatedOverlays(kind, required, excluded) {
  const canonicalDir = join(REPO, kind);
  const overlayDir = join(canonicalDir, 'codex');
  const baselinePath = join(canonicalDir, 'codex-baseline.json');
  const canonical = new Map(
    readdirSync(canonicalDir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
      .map((entry) => {
        const slug = basename(entry.name, '.md');
        return [slug, readFileSync(join(canonicalDir, entry.name), 'utf8')];
      }),
  );
  const overlayFiles = flatMarkdownFiles(overlayDir, `${kind}/codex overlays`);
  const overlays = new Map(overlayFiles.map((file) => [
    basename(file, '.md'),
    readFileSync(join(overlayDir, file), 'utf8'),
  ]));

  for (const slug of overlays.keys()) {
    if (!canonical.has(slug)) throw new Error(`orphan ${kind} Codex override: ${slug}`);
    if (excluded.has(slug)) throw new Error(`excluded ${kind} must not have a Codex override: ${slug}`);
  }
  assertSameSet(new Set(overlays.keys()), required, `${kind} required Codex overrides`);

  const baseline = readJson(baselinePath, `${kind} Codex baseline`);
  if (baseline.schema_version !== 1 || baseline.algorithm !== 'sha256' || !baseline.overrides) {
    throw new Error(`${kind} Codex baseline has an unsupported schema: ${baselinePath}`);
  }
  assertSameSet(new Set(Object.keys(baseline.overrides)), new Set(overlays.keys()), `${kind} baseline entries`);
  for (const [slug, expectedHash] of Object.entries(baseline.overrides)) {
    const actualHash = sha256(canonical.get(slug));
    if (actualHash !== expectedHash) {
      throw new Error(`canonical ${kind}/${slug}.md changed; review ${kind}/codex/${slug}.md and refresh its baseline intentionally`);
    }
  }
  return { canonical, overlays };
}

function splitFrontmatter(text) {
  if (!text.startsWith('---')) return { meta: {}, body: text };
  const end = text.indexOf('\n---', 3);
  if (end === -1) return { meta: {}, body: text };
  const raw = text.slice(4, end);
  const body = text.slice(end + 4).replace(/^\n+/, '');
  const meta = {};
  let key = null;
  for (const line of raw.split('\n')) {
    const m = line.match(/^([a-zA-Z_][\w-]*):\s*(.*)$/);
    if (m) {
      key = m[1];
      meta[key] = m[2].trim().replace(/^["'](.*)["']$/s, '$1');
    } else if (key && /^\s*-\s+/.test(line)) {
      meta[key] = [].concat(meta[key] === '' ? [] : meta[key], line.replace(/^\s*-\s+/, '').trim());
    }
  }
  return { meta, body };
}

/** TOML multi-line string that survives regexes and backslashes in prose. */
function tomlBlock(text) {
  if (!text.includes("'''")) return `'''\n${text}\n'''`;
  return `"""\n${text.replaceAll('\\', '\\\\').replaceAll('"""', '\\"\\"\\"')}\n"""`;
}
const tomlString = (s) => `"${String(s).replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;

