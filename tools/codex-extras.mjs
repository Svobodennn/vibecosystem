function normalizeAgentSource(text) {
  return text.replace(/\r\n/g, '\n').replaceAll('-Users-svoboden', '<project-slug>');
}

function applyLiteralSpecs(slug, parts, specs, label) {
  const next = { ...parts, meta: { ...parts.meta } };
  for (const [targetSlug, field, needle, replacement] of specs) {
    if (targetSlug !== slug) continue;
    const source = field === 'description' ? String(next.meta.description || '') : next.body;
    const matches = source.split(needle).length - 1;
    if (matches !== 1) {
      throw new Error(`${label} ${slug}.${field} expectedMatches=1, observed=${matches}: ${needle}`);
    }
    if (field === 'description') next.meta.description = source.replace(needle, replacement);
    else next.body = source.replace(needle, replacement);
  }
  return next;
}

function stripWorktreeProtocol(text) {
  const lines = text.split('\n');
  const kept = [];
  let skipping = false;
  for (const line of lines) {
    if (/^##\s+(?:Worktree Handoff|GIT WORKTREE PROTOKOLU)\b/i.test(line)) {
      skipping = true;
      continue;
    }
    if (skipping && /^#{1,2}\s+/.test(line)) skipping = false;
    if (!skipping && !/\bisolation:\s*worktree\b/i.test(line)) kept.push(line);
  }
  return kept.join('\n');
}

function adaptCodexPaths(text) {
  let adapted = text
    .replace(/^\$CLAUDE_PROJECT_DIR\s*=.*$/gm, 'Project root: current working directory (`$PWD`).')
    .replaceAll('$CLAUDE_PROJECT_DIR', '$PWD')
    .replace(/~\/\.claude\/rules\/([\w-]+)\.md/g, '~/.agents/skills/rule-$1/SKILL.md')
    .replaceAll('~/.claude/agents/', '~/.codex/agents/')
    .replaceAll('CLAUDE.md', 'AGENTS.md')
    .replaceAll('parent Claude', 'parent context')
    .replaceAll('Parent Claude', 'Parent context')
    .replaceAll('Claude Code', 'Codex');
  adapted = adapted.split('\n').filter((line) => {
    if (/\.claude\//.test(line)) return false;
    if (/<project-slug>/.test(line)) return false;
    return true;
  }).join('\n');
  return adapted.replace(/\n{3,}/g, '\n\n').trim();
}

function mechanicalAgentTransform(parts) {
  const meta = { description: String(parts.meta.description || '').trim() };
  let body = adaptCodexPaths(stripWorktreeProtocol(parts.body));
  if (!body.includes('## Codex leaf-agent contract')) body = `${body}\n\n${LEAF_CONTRACT}`;
  return { meta, body: body.trim() };
}

function assertAgentTransformIdempotent(slug, transformed) {
  const second = mechanicalAgentTransform(transformed);
  if (second.meta.description !== transformed.meta.description || second.body !== transformed.body) {
    throw new Error(`Codex agent transform is not idempotent for ${slug}`);
  }
}

function personaNickname(slug, description) {
  const matches = [...description.matchAll(/\(([^(),]+?) persona\)/gu)];
  if (matches.length > 1) throw new Error(`agent ${slug} has multiple persona names in its description`);
  if (!matches.length) return null;
  const nickname = matches[0][1].trim();
  if (!nickname || !nickname.includes(' ')) {
    throw new Error(`agent ${slug} has an invalid persona name in its description: ${nickname}`);
  }
  return nickname;
}

function validateLiveAgentMirror(canonical) {
  const liveFiles = flatMarkdownFiles(CLAUDE_AGENTS, 'live Claude agents', { ignoreDotfiles: true });
  if (liveFiles.length !== 131) throw new Error(`expected 131 live Claude agents, found ${liveFiles.length}`);
  for (const file of liveFiles) {
    const slug = basename(file, '.md');
    if (!canonical.has(slug)) throw new Error(`live Claude agent has no canonical repo source: ${slug}`);
    const live = normalizeAgentSource(readFileSync(join(CLAUDE_AGENTS, file), 'utf8'));
    const repo = normalizeAgentSource(canonical.get(slug));
    if (live !== repo) throw new Error(`live Claude agent differs from canonical content beyond project placeholder: ${slug}`);
  }
  return liveFiles;
}

function managedAgentRegistry(agents) {
  const lines = [
    REGISTRY_START,
    '[agents]',
    'max_concurrent_threads_per_session = 4',
    'max_depth = 1',
  ];
  for (const agent of agents) {
    const roleLines = [
      '',
      `[agents.${agent.role}]`,
      `description = ${tomlString(agent.description)}`,
      `config_file = ${tomlString(`agents/${agent.slug}.toml`)}`,
    ];
    if (agent.nickname) roleLines.push(`nickname_candidates = [${tomlString(agent.nickname)}]`);
    lines.push(...roleLines);
  }
  lines.push(REGISTRY_END);
  return `${lines.join('\n')}\n`;
}

